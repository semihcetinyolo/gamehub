#!/usr/bin/env python3
"""Copy the two cocktail games into this folder for the combined page.

    v1/ <- ../cocktail_sort   (Cocktail Sort)
    v2/ <- ../cocktail_flow   (Cocktail Flow)

Each game's scripts, style.css and assets/img are copied as they are; its
<body> markup and script list go into v<N>/mount.js, which index.html
reads when the V1 / V2 button is pressed. Rerun after changing
either game:  python3 cafe_sort/build.py
"""
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAMES = {"v1": HERE.parent / "cocktail_sort", "v2": HERE.parent / "cocktail_flow"}
IMG_SKIP = {"belt_v1.png", "belt_v2.png", "belt_v3.png"}   # archived belt art, unused


def build(key: str, src: Path):
    out = HERE / key
    if out.exists():
        shutil.rmtree(out)
    (out / "assets").mkdir(parents=True)

    html = (src / "index.html").read_text(encoding="utf-8")
    title = re.search(r"<title>(.*?)</title>", html, re.S).group(1).strip()
    scripts = re.findall(r'<script src="([^"]+)"></script>', html)
    styles = re.findall(r'<link rel="stylesheet" href="([^"]+)">', html)
    body = re.search(r"<body>(.*?)<script", html, re.S).group(1).strip()

    for f in scripts + styles:
        text = (src / f).read_text(encoding="utf-8")
        if f == "assets.js":   # art paths are relative to the page, not the script
            text, n = re.subn(r"const DIR = 'assets/img/';", f"const DIR = '{key}/assets/img/';", text)
            assert n == 1, f"{src.name}/assets.js: DIR line not found"
        (out / f).parent.mkdir(parents=True, exist_ok=True)   # e.g. tools/solver.js
        (out / f).write_text(text, encoding="utf-8")
    shutil.copytree(src / "assets" / "img", out / "assets" / "img",
                    ignore=lambda d, names: [n for n in names if n in IMG_SKIP or n.startswith(".")])

    mount = {
        "title": title,
        "body": body,
        "styles": [f"{key}/{f}" for f in styles],
        "scripts": [f"{key}/{f}" for f in scripts],
    }
    (out / "mount.js").write_text(
        f"// GENERATED by build.py from ../{src.name}/index.html\n"
        f"(window.CAFE_GAMES = window.CAFE_GAMES || {{}})[{json.dumps(key)}] = "
        + json.dumps(mount, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8")
    print(f"{key}: {title} ({len(scripts)} scripts)")


for k, s in GAMES.items():
    build(k, s)
