#!/usr/bin/env python3
"""Leaderboard and profile art for Pixhaku -> leaderboard_art.js

Put the generated pictures in assets/leaderboard/src/ under the names below (png, jpg or
webp, any size). This script crops and scales each one, writes assets/leaderboard/<name>.png
and bundles them all as data URLs into leaderboard_art.js, which the prototype loads before
leaderboard.js. Pictures that don't exist yet are drawn in code by leaderboard.js.

Transparent pictures: if a source has no transparency but a flat background (the four corners
share one colour), that background is removed by flood fill from the edges.

Usage: python3 tools/build_lb_art.py
"""
import base64
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "leaderboard" / "src"
OUT = ROOT / "assets" / "leaderboard"
BUNDLE = ROOT / "leaderboard_art.js"

# name: (width, height, mode)   cover = square crop, opaque · fit = trim + fit, transparent
SPECS = {
    **{f"avatar-{i}": (192, 192, "cover") for i in range(1, 10)},
    **{f"medal-{i}": (96, 96, "fit") for i in range(1, 4)},
    **{f"chest-{i}": (256, 256, "fit") for i in range(1, 4)},
    **{f"chest-{i}-open": (256, 256, "fit") for i in range(1, 4)},
    "leaderboard-icon": (128, 128, "fit"),
    "champion-frame": (256, 256, "frame"),
    "season-banner": (640, 320, "fit"),
}


def find_source(name):
    for ext in (".png", ".webp", ".jpg", ".jpeg"):
        path = SRC / f"{name}{ext}"
        if path.exists():
            return path
    return None


def drop_flat_background(img, tolerance=40):
    """Make an edge-connected flat background transparent (sources saved without alpha)."""
    img = img.convert("RGBA")
    w, h = img.size
    px = img.load()
    corners = [px[0, 0], px[w - 1, 0], px[0, h - 1], px[w - 1, h - 1]]
    base = corners[0]
    close = lambda a, b: sum(abs(a[k] - b[k]) for k in range(3)) <= tolerance
    if not all(close(c, base) for c in corners):
        return img, False
    seen = bytearray(w * h)
    stack = [(x, y) for x in range(w) for y in (0, h - 1)] + [(x, y) for y in range(h) for x in (0, w - 1)]
    while stack:
        x, y = stack.pop()
        i = y * w + x
        if seen[i]:
            continue
        seen[i] = 1
        if not close(px[x, y], base):
            continue
        px[x, y] = (0, 0, 0, 0)
        if x > 0: stack.append((x - 1, y))
        if x < w - 1: stack.append((x + 1, y))
        if y > 0: stack.append((x, y - 1))
        if y < h - 1: stack.append((x, y + 1))
    return img, True


def has_alpha(img):
    return img.mode in ("RGBA", "LA") and img.getchannel("A").getextrema()[0] < 250


def prepare(name, path):
    w, h, mode = SPECS[name]
    img = Image.open(path)
    note = ""
    if mode == "cover":
        img = img.convert("RGB")
        side = min(img.size)
        left, top = (img.width - side) // 2, (img.height - side) // 2
        return img.crop((left, top, left + side, top + side)).resize((w, h), Image.LANCZOS), note
    img = img.convert("RGBA")
    if not has_alpha(img):
        img, removed = drop_flat_background(img)
        note = "background removed" if removed else "!! no transparency"
    box = img.getchannel("A").getbbox()
    if box:
        img = img.crop(box)
    if mode == "frame":  # the frame fills the square exactly, so it lines up with the avatar
        return img.resize((w, h), Image.LANCZOS), note
    scale = min(w / img.width, h / img.height)
    img = img.resize((max(1, round(img.width * scale)), max(1, round(img.height * scale))), Image.LANCZOS)
    canvas = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    canvas.paste(img, ((w - img.width) // 2, (h - img.height) // 2), img)
    return canvas, note


def main():
    SRC.mkdir(parents=True, exist_ok=True)
    art, missing = {}, []
    for name in SPECS:
        src = find_source(name)
        out = OUT / f"{name}.png"
        if src:
            img, note = prepare(name, src)
            img.save(out, optimize=True)
            print(f"  {name:<18} {img.width}x{img.height}  {note}")
        elif not out.exists():
            missing.append(name)
            continue
        data = base64.b64encode(out.read_bytes()).decode()
        art[name] = f"data:image/png;base64,{data}"
    js = ("// Generated by tools/build_lb_art.py from assets/leaderboard/. Don't edit by hand.\n"
          f"window.PIXHAKU_LB_ART = {json.dumps(art, indent=0)};\n")
    BUNDLE.write_text(js, encoding="utf-8")
    print(f"leaderboard_art.js: {len(art)} pictures, {BUNDLE.stat().st_size / 1024:.0f} KB")
    if missing:
        print("still drawn in code:", ", ".join(missing))


if __name__ == "__main__":
    main()
